-- Grupos de promoción (pedido del usuario, 2026-11-01: "que se armen promo de productos y cambie ese
-- valor", como en Somnia; traído de Central el mismo día, donde es la 037). Los productos de un mismo
-- grupo suman juntos para llegar al precio por
-- cantidad de cada uno: unidades con unidades y cajas con cajas (decisión del usuario). Cada producto
-- conserva su propio "desde N" y su precio. Los arma, cambia y borra solo el Administrador.
-- Aditiva: tabla nueva y columnas opcionales; ningún producto queda en un grupo hasta que el Admin lo
-- arme, y las ventas y pedidos ya hechos no cambian.
CREATE TABLE grupos_promocion (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  actualizado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  eliminado_en TIMESTAMP(0)
);
-- Nombre único entre los grupos activos, sin distinguir mayúsculas (como los catálogos).
CREATE UNIQUE INDEX idx_grupos_promocion_nombre_activo ON grupos_promocion (LOWER(nombre)) WHERE eliminado_en IS NULL;

-- El grupo con que suma el producto (NULL: cuenta solo). Al eliminar un grupo, sus productos quedan
-- sin grupo: nunca apunta a uno eliminado.
ALTER TABLE productos ADD COLUMN grupo_promocion_id INTEGER REFERENCES grupos_promocion(id);
CREATE INDEX idx_productos_grupo_promocion ON productos(grupo_promocion_id) WHERE grupo_promocion_id IS NOT NULL;

-- Cada línea guarda una copia del nombre del grupo si llegó al precio por cantidad con él, junto a
-- precio_cantidad_desde (solo para mostrar, igual que el pack).
ALTER TABLE venta_items ADD COLUMN precio_cantidad_grupo VARCHAR(60);
ALTER TABLE pedido_cliente_items ADD COLUMN precio_cantidad_grupo VARCHAR(60);
