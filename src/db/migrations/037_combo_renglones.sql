-- Combos por renglones con varias marcas (pedido del usuario, 2026-11-01: "una promoción puede estar
-- armada por productos de diferente marca, el sistema debe detectar eso"; aprobó la maqueta). Un
-- combo lleva renglones ("Fernet", "Cola"): cada uno con su forma (suelto o la caja o pack de cada
-- marca), su cantidad y las marcas que valen. En Caja cualquier marca del renglón cuenta, mezcladas
-- (1 Coca + 1 Pepsi = 2 colas). Reemplaza a combo_items (036), que queda sin uso y no se borra.
CREATE TABLE combo_renglones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  combo_id INTEGER NOT NULL REFERENCES combos(id),
  nombre VARCHAR(60) NOT NULL,
  presentacion TEXT NOT NULL CHECK (presentacion IN ('unidad', 'pack')),
  -- Suelto: en la medida chica (unidades, gramos o ml); pack: en packs de cada marca.
  cantidad INTEGER NOT NULL CHECK (cantidad > 0 AND cantidad <= 10000000),
  -- De qué fila de combo_items salió al pasar los combos de la 036 a renglones (si salió de ahí).
  combo_item_id INTEGER REFERENCES combo_items(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  actualizado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  eliminado_en TIMESTAMP(0)
);
CREATE INDEX idx_combo_renglones_combo ON combo_renglones (combo_id);

-- Las marcas que valen en cada renglón. Sacar una es una baja lógica.
CREATE TABLE combo_renglon_productos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  renglon_id INTEGER NOT NULL REFERENCES combo_renglones(id),
  producto_id INTEGER NOT NULL REFERENCES productos(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  eliminado_en TIMESTAMP(0)
);
CREATE UNIQUE INDEX idx_combo_renglon_productos_activo ON combo_renglon_productos (renglon_id, producto_id) WHERE eliminado_en IS NULL;

-- Lo que ya estaba cargado: cada producto de un combo pasa a ser un renglón con su nombre, su forma,
-- su cantidad y esa sola marca.
INSERT INTO combo_renglones (combo_id, nombre, presentacion, cantidad, combo_item_id, creado_en)
SELECT ci.combo_id, LEFT(p.nombre, 60), ci.presentacion, ci.cantidad, ci.id, ci.creado_en
FROM combo_items ci
JOIN productos p ON p.id = ci.producto_id
WHERE ci.eliminado_en IS NULL
ORDER BY ci.id;

INSERT INTO combo_renglon_productos (renglon_id, producto_id, creado_en)
SELECT r.id, ci.producto_id, ci.creado_en
FROM combo_renglones r
JOIN combo_items ci ON ci.id = r.combo_item_id
ORDER BY r.id;
