-- Saldos pendientes → Proveedores a mano (pedido del usuario, 2026-10-29: "ya se cargaron cosas,
-- pero no están finos los valores"): corregir una boleta (comprobante, número, fecha y total, como
-- dicen la factura o el remito) y cargar una deuda con un proveedor sin cargar mercadería.
-- Aditiva: columnas y una tabla nuevas; el CHECK del comprobante se amplía (ningún dato cambia).

-- Deuda cargada a mano: una compra sin líneas (no toca el stock), con una nota opcional. Puede no
-- tener comprobante ('sin').
ALTER TABLE compras_proveedor ADD COLUMN cargada_a_mano BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE compras_proveedor ADD COLUMN nota TEXT CHECK (char_length(nota) <= 200);
-- El CHECK de la 028 se busca por lo que controla, no por su nombre (no depende de cómo lo nombró
-- Postgres).
DO $$
DECLARE c record;
BEGIN
  FOR c IN
    SELECT conname FROM pg_constraint
    WHERE conrelid = 'compras_proveedor'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%comprobante_tipo%'
  LOOP
    EXECUTE format('ALTER TABLE compras_proveedor DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;
ALTER TABLE compras_proveedor ADD CONSTRAINT compras_proveedor_comprobante_tipo_check
  CHECK (comprobante_tipo IN ('remito', 'factura', 'sin'));

-- Cada corrección de una boleta: lo que tenía y lo que quedó, el motivo, quién y cuándo. La compra
-- guarda los valores corregidos (así el saldo y los pagos usan el total real) y lo de antes no se
-- pierde. El stock y los costos de los productos no cambian.
CREATE TABLE correcciones_compra (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id INTEGER NOT NULL REFERENCES compras_proveedor(id),
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  motivo TEXT NOT NULL CHECK (char_length(motivo) BETWEEN 1 AND 200),
  antes_tipo TEXT NOT NULL,
  antes_numero TEXT,
  antes_fecha DATE NOT NULL,
  antes_total BIGINT NOT NULL,
  despues_tipo TEXT NOT NULL,
  despues_numero TEXT,
  despues_fecha DATE NOT NULL,
  despues_total BIGINT NOT NULL,
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_correcciones_compra_compra ON correcciones_compra(compra_id);
