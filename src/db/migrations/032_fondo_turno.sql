-- arranca con un importe en caja y no tengo donde ponerlo"; traído a CEAVital el mismo día, en Central es la 034).
-- Hasta ahora el fondo de un turno salía
-- solo del que dejó el cierre anterior, así que el primer turno arrancaba siempre en 0.
-- Cada fila es el fondo de un turno: el que sigue al cierre desde_cierre_id (NULL: el turno de antes
-- del primer cierre). Corregirlo agrega otra fila y vale la última: nada se pisa ni se borra.
-- Aditiva: tabla nueva.
CREATE TABLE fondos_turno (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  desde_cierre_id INTEGER REFERENCES cierres_caja(id),
  monto BIGINT NOT NULL CHECK (monto >= 0),
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_fondos_turno_cierre ON fondos_turno(desde_cierre_id, id);
