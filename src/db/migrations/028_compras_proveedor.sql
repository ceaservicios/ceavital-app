-- Mercaderia que trae un proveedor y lo que se le paga (pedido del usuario, 2026-10-28): se carga
-- lo que trajo con fecha y remito o factura, cada linea entra al stock como un lote, y en el
-- perfil del proveedor queda lo que se le compro y si se le pago todo, una parte o nada.
-- Los pedidos a proveedor de antes (pedidos_proveedor) ya no se cargan: quedan como historial.
-- Aditiva: tablas nuevas, no toca datos existentes.

-- Una compra: lo que entro con un remito o una factura. No se borra: anularla (si no se vendio
-- nada de lo que entro y no tiene pagos) retira sus lotes del stock y la deja en el historial.
CREATE TABLE compras_proveedor (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id INTEGER NOT NULL REFERENCES proveedores(id),
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  fecha DATE NOT NULL,
  comprobante_tipo TEXT NOT NULL CHECK (comprobante_tipo IN ('remito', 'factura')),
  comprobante_numero TEXT CHECK (char_length(comprobante_numero) <= 50),
  total BIGINT NOT NULL CHECK (total >= 0),
  anulada_en TIMESTAMP(0),
  anulada_por INTEGER REFERENCES usuarios(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_compras_proveedor_proveedor ON compras_proveedor(proveedor_id, fecha);

-- Cada linea crea su lote (lote_id) y guarda como se cargo: la cantidad en la medida chica
-- (unidades, gramos o ml) y, si fue en packs, la copia del pack y cuantos packs. El costo es el
-- de esa presentacion (por pack, por unidad o por kg/litro).
CREATE TABLE compra_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id INTEGER NOT NULL REFERENCES compras_proveedor(id),
  producto_id INTEGER NOT NULL REFERENCES productos(id),
  lote_id INTEGER NOT NULL REFERENCES lotes(id),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  pack_nombre TEXT,
  pack_unidades INTEGER,
  cantidad_presentacion INTEGER,
  costo_unitario BIGINT NOT NULL CHECK (costo_unitario >= 0),
  subtotal BIGINT NOT NULL CHECK (subtotal >= 0),
  fecha_vencimiento DATE,
  CHECK ((pack_nombre IS NULL) = (pack_unidades IS NULL) AND (pack_nombre IS NULL) = (cantidad_presentacion IS NULL))
);
CREATE INDEX idx_compra_items_compra ON compra_items(compra_id);
CREATE UNIQUE INDEX idx_compra_items_lote ON compra_items(lote_id);

-- Un pago a un proveedor, siempre de una compra. En efectivo se elige si sale de la caja: si
-- sale, se anota tambien como gasto de caja (gasto_caja_id) y cuenta en el arqueo del turno.
-- No se borra: anularlo lo deja en el historial y da de baja ese gasto.
CREATE TABLE pagos_proveedor (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id INTEGER NOT NULL REFERENCES proveedores(id),
  compra_id INTEGER NOT NULL REFERENCES compras_proveedor(id),
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  fecha DATE NOT NULL,
  monto BIGINT NOT NULL CHECK (monto > 0),
  medio TEXT NOT NULL CHECK (medio IN ('efectivo', 'mercado_pago', 'cheque')),
  sale_de_caja BOOLEAN NOT NULL DEFAULT FALSE,
  gasto_caja_id INTEGER REFERENCES gastos_caja(id),
  cheque_numero TEXT CHECK (char_length(cheque_numero) <= 50),
  cheque_banco TEXT CHECK (char_length(cheque_banco) <= 100),
  cheque_fecha_cobro DATE,
  detalle TEXT CHECK (char_length(detalle) <= 200),
  anulado_en TIMESTAMP(0),
  anulado_por INTEGER REFERENCES usuarios(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  CHECK (sale_de_caja = FALSE OR medio = 'efectivo'),
  CHECK ((gasto_caja_id IS NOT NULL) = sale_de_caja)
);
CREATE INDEX idx_pagos_proveedor_proveedor ON pagos_proveedor(proveedor_id);
CREATE INDEX idx_pagos_proveedor_compra ON pagos_proveedor(compra_id);
CREATE UNIQUE INDEX idx_pagos_proveedor_gasto ON pagos_proveedor(gasto_caja_id);
