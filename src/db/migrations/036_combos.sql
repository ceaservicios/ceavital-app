-- Combos con precio (pedido del usuario, 2026-11-01: "en esa promoción se debe poder elegir si se vende
-- por unidad / caja / pack... cantidades"; eligió "combo con precio"). Un combo es un conjunto fijo de
-- productos, cada uno con su forma (suelto o su pack) y su cantidad, y un precio total. En Caja se
-- cobra solo cuando el carrito tiene todo lo del combo (las veces que entre); lo que sobra va a su
-- precio normal. Sin fecha y solo en Caja (decisiones del usuario). Los arma solo el Administrador.
-- Aditiva: tablas nuevas y columnas opcionales; las ventas ya hechas no cambian.
CREATE TABLE combos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  precio BIGINT NOT NULL CHECK (precio > 0 AND precio <= 1000000000),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  actualizado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  eliminado_en TIMESTAMP(0)
);
-- Nombre único entre los combos activos, sin distinguir mayúsculas (como los grupos).
CREATE UNIQUE INDEX idx_combos_nombre_activo ON combos (LOWER(nombre)) WHERE eliminado_en IS NULL;

-- Lo que trae cada combo. presentacion: 'unidad' (suelto: unidades, o gramos/ml en kg/litro) o
-- 'pack' (cantidad en packs del producto), lo mismo que una línea de Caja. Sacar un producto es una
-- baja lógica; un mismo producto va una sola vez por forma en cada combo.
CREATE TABLE combo_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  combo_id INTEGER NOT NULL REFERENCES combos(id),
  producto_id INTEGER NOT NULL REFERENCES productos(id),
  presentacion TEXT NOT NULL CHECK (presentacion IN ('unidad', 'pack')),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0 AND cantidad <= 10000000),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  actualizado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  eliminado_en TIMESTAMP(0)
);
CREATE UNIQUE INDEX idx_combo_items_activo ON combo_items (combo_id, producto_id, presentacion) WHERE eliminado_en IS NULL;
CREATE INDEX idx_combo_items_combo ON combo_items (combo_id);

-- Cada línea de venta que entró en un combo guarda el combo y una copia de su nombre (para mostrar,
-- como el grupo y el pack). El precio del combo se reparte entre sus líneas.
ALTER TABLE venta_items ADD COLUMN combo_id INTEGER REFERENCES combos(id);
ALTER TABLE venta_items ADD COLUMN combo_nombre VARCHAR(60);
