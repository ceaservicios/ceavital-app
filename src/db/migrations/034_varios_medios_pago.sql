-- Varios medios de pago en una venta (pedido del usuario, 2026-11-01; traído de Central el mismo día,
-- donde es la 036): una venta se cobra repartida
-- entre Efectivo, Tarjeta, Transferencia / QR, Mercado Pago y Pago pendiente (una parte puede quedar
-- debiendo, decisión del usuario). Esa venta guarda medio_pago = 'mixto' y cada parte va en
-- venta_pagos; las de un solo medio siguen como siempre, sin filas acá. Cuenta corriente no se
-- reparte: carga el total de la venta a la deuda del cliente.
-- Aditiva: un valor más en el CHECK de ventas.medio_pago (el de la 001) y una tabla nueva.
ALTER TABLE ventas DROP CONSTRAINT IF EXISTS ventas_medio_pago_check;
ALTER TABLE ventas ADD CONSTRAINT ventas_medio_pago_check CHECK (
  medio_pago IN ('efectivo', 'tarjeta', 'transferencia_qr', 'mercado_pago', 'fiado', 'cta_cte', 'mixto')
);

CREATE TABLE venta_pagos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id INTEGER NOT NULL REFERENCES ventas(id),
  medio_pago TEXT NOT NULL CHECK (medio_pago IN ('efectivo', 'tarjeta', 'transferencia_qr', 'mercado_pago', 'fiado')),
  monto BIGINT NOT NULL CHECK (monto > 0),
  UNIQUE (venta_id, medio_pago)
);
