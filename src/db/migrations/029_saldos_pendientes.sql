-- Saldos pendientes (pedido del usuario, 2026-10-29): impuestos, servicios y gastos fijos que hay
-- que pagar (alquiler, luz, agua, internet...), con su vencimiento y, si se repiten, cada cuanto.
-- Lo que se debe a los proveedores ya esta en compras_proveedor / pagos_proveedor.
-- Aditiva: tablas nuevas, no toca datos existentes.

-- Una cuenta a pagar. Si se repite, al quedar pagada se crea sola la siguiente (origen_id = esta,
-- una sola por cuenta). Su vencimiento se cuenta desde serie_base (serie_numero periodos despues),
-- asi una cuenta que vence el 31 no queda corrida al 28 para siempre despues de febrero.
CREATE TABLE cuentas_pagar (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo TEXT NOT NULL CHECK (tipo IN ('impuestos', 'alquiler', 'luz', 'agua', 'gas', 'internet', 'honorarios', 'otro')),
  concepto TEXT NOT NULL CHECK (char_length(concepto) BETWEEN 1 AND 200),
  monto BIGINT NOT NULL CHECK (monto > 0),
  vence DATE NOT NULL,
  repeticion TEXT NOT NULL DEFAULT 'no' CHECK (repeticion IN ('no', 'semanal', 'quincenal', 'mensual', 'bimestral', 'anual')),
  nota TEXT CHECK (char_length(nota) <= 200),
  serie_base DATE NOT NULL,
  serie_numero INTEGER NOT NULL DEFAULT 0 CHECK (serie_numero >= 0),
  origen_id INTEGER REFERENCES cuentas_pagar(id),
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  actualizado_en TIMESTAMP(0),
  eliminado_en TIMESTAMP(0)
);
CREATE INDEX idx_cuentas_pagar_vence ON cuentas_pagar(vence);
CREATE UNIQUE INDEX idx_cuentas_pagar_origen ON cuentas_pagar(origen_id);

-- Un pago de una cuenta (puede ser en partes). Igual que con los proveedores: en efectivo se elige
-- si sale de la caja y, si sale, se anota tambien como gasto de caja. No se borra: se anula.
CREATE TABLE pagos_cuenta (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuenta_id INTEGER NOT NULL REFERENCES cuentas_pagar(id),
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  fecha DATE NOT NULL,
  monto BIGINT NOT NULL CHECK (monto > 0),
  medio TEXT NOT NULL CHECK (medio IN ('efectivo', 'transferencia', 'mercado_pago', 'debito', 'tarjeta')),
  sale_de_caja BOOLEAN NOT NULL DEFAULT FALSE,
  gasto_caja_id INTEGER REFERENCES gastos_caja(id),
  detalle TEXT CHECK (char_length(detalle) <= 200),
  anulado_en TIMESTAMP(0),
  anulado_por INTEGER REFERENCES usuarios(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  CHECK (sale_de_caja = FALSE OR medio = 'efectivo'),
  CHECK ((gasto_caja_id IS NOT NULL) = sale_de_caja)
);
CREATE INDEX idx_pagos_cuenta_cuenta ON pagos_cuenta(cuenta_id);
CREATE UNIQUE INDEX idx_pagos_cuenta_gasto ON pagos_cuenta(gasto_caja_id);
