-- Lo que CEA le cobra a la empresa pasa a ser en dolares (decision del usuario, 2026-10-21; panel
-- /sa > Cuota y pagos): la implementacion en cuotas con recargo, un abono mensual y las
-- modificaciones solicitadas (las primeras sin cargo). Cada mes hay un aviso (el del vencimiento
-- pendiente, instancia.cuota_vence) que se paga completo, y cada pago guarda la foto de lo que pago.
-- Aditiva: columnas nuevas en `instancia` y `pagos_cuota` y una tabla nueva; no cambia ni borra
-- ningun dato. instancia.cuota_monto (el importe en pesos de la 021) queda como esta, sin uso.
--
-- Montos en dolares: en centavos (BIGINT), de 1 a 100.000.000 (USD 1.000.000).

-- Implementacion, abono y modificaciones sin cargo: en `instancia` (una sola fila, de CEA) y no en
-- una tabla propia de una fila. Al restaurar una copia, `instancia` se trae de la base de recien;
-- una tabla nueva sembrada por esta migracion chocaria con esa fila al restaurar una copia
-- anterior a la 026 (la fila 1 quedaria dos veces y la restauracion fallaria).
ALTER TABLE instancia ADD COLUMN impl_valor_usd BIGINT CHECK (impl_valor_usd BETWEEN 1 AND 100000000);
ALTER TABLE instancia ADD COLUMN impl_recargo NUMERIC(5, 2) CHECK (impl_recargo BETWEEN 0 AND 100);
ALTER TABLE instancia ADD COLUMN impl_cuotas SMALLINT CHECK (impl_cuotas BETWEEN 1 AND 120);
ALTER TABLE instancia ADD COLUMN impl_primera_vence DATE;
ALTER TABLE instancia ADD CONSTRAINT instancia_impl_completa CHECK (
  (impl_valor_usd IS NULL AND impl_recargo IS NULL AND impl_cuotas IS NULL AND impl_primera_vence IS NULL)
  OR (impl_valor_usd IS NOT NULL AND impl_recargo IS NOT NULL AND impl_cuotas IS NOT NULL AND impl_primera_vence IS NOT NULL)
);

-- Abono mensual, sin fin: que incluye (una linea) y el importe por mes.
ALTER TABLE instancia ADD COLUMN abono_detalle TEXT CHECK (char_length(abono_detalle) BETWEEN 1 AND 200);
ALTER TABLE instancia ADD COLUMN abono_usd BIGINT CHECK (abono_usd BETWEEN 1 AND 100000000);
ALTER TABLE instancia ADD CONSTRAINT instancia_abono_completo CHECK ((abono_detalle IS NULL) = (abono_usd IS NULL));

-- Cuantas modificaciones son sin cargo en todo el contrato (no se renuevan por mes).
ALTER TABLE instancia ADD COLUMN modif_sin_cargo SMALLINT NOT NULL DEFAULT 0 CHECK (modif_sin_cargo BETWEEN 0 AND 100);

-- Pagos: los que ya estan siguen en pesos (moneda 'ARS'); los nuevos van en dolares, en centavos,
-- con la foto del aviso que pagaron (cuota de la implementacion, abono, modificaciones con costo y
-- total), asi el historial no cambia si despues se edita la configuracion. Una cuota de la
-- implementacion esta pagada si un pago no anulado tiene su numero en la foto.
ALTER TABLE pagos_cuota ADD COLUMN moneda TEXT NOT NULL DEFAULT 'ARS' CHECK (moneda IN ('ARS', 'USD'));
ALTER TABLE pagos_cuota ADD COLUMN desglose JSONB;
ALTER TABLE pagos_cuota ADD CONSTRAINT pagos_cuota_usd CHECK (moneda = 'ARS' OR (monto <= 100000000 AND desglose IS NOT NULL));

-- Modificaciones solicitadas. sin_cargo: se anoto mientras quedaban sin cargo (sin importe). aviso:
-- el vencimiento en el que se cobra (las con costo) o en el que sale por primera vez en el mail (las
-- sin cargo): el primero de la serie de vencimientos posterior a la fecha y no anterior al
-- vencimiento pendiente de ese momento. Nunca se borra: se anula con un motivo.
CREATE TABLE modificaciones_cuota (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha DATE NOT NULL,
  detalle TEXT NOT NULL CHECK (char_length(detalle) BETWEEN 1 AND 200),
  sin_cargo BOOLEAN NOT NULL,
  importe_usd BIGINT CHECK (importe_usd BETWEEN 1 AND 100000000),
  aviso DATE NOT NULL,
  anulada_en TIMESTAMP(0),
  anulada_motivo TEXT CHECK (char_length(anulada_motivo) <= 500),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  CONSTRAINT modificaciones_cuota_importe CHECK (sin_cargo = (importe_usd IS NULL))
);
CREATE INDEX idx_modificaciones_cuota_fecha ON modificaciones_cuota (fecha DESC, id DESC);
