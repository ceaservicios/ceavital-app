-- En Central es la migración 043.
-- Fijos (pedido del usuario, 2026-11-06; maqueta aprobada): lo que se paga siempre. Reemplaza a la
-- repeticion de Saldos pendientes, donde la cuenta siguiente aparecia recien al pagar la anterior.
-- Ahora cada vencimiento entra a Saldos pendientes por fecha, 30 dias antes, aunque el anterior siga
-- sin pagar, y se paga como cualquier otra cuenta.
-- Preserva los datos: tabla y columna nuevas, y el monto de una cuenta pasa a ser opcional.

--   monto           NULL = "segun factura": cambia cada vez y se escribe al pagar
--   desde           el vencimiento desde el que se cuentan los demas, asi uno que vence el 31 no queda
--                   corrido al 28 para siempre despues de febrero
--   generado_hasta  el ultimo vencimiento que ya entro a Saldos pendientes
CREATE TABLE fijos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo TEXT NOT NULL CHECK (tipo IN ('impuestos', 'alquiler', 'luz', 'agua', 'gas', 'internet', 'honorarios', 'otro')),
  concepto TEXT NOT NULL CHECK (char_length(concepto) BETWEEN 1 AND 200),
  monto BIGINT CHECK (monto > 0),
  frecuencia TEXT NOT NULL CHECK (frecuencia IN ('semanal', 'quincenal', 'mensual', 'bimestral', 'anual')),
  desde DATE NOT NULL,
  generado_hasta DATE,
  nota TEXT CHECK (char_length(nota) <= 200),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  actualizado_en TIMESTAMP(0),
  eliminado_en TIMESTAMP(0)
);

-- Un vencimiento sin monto no tiene uno hasta que se paga.
ALTER TABLE cuentas_pagar ALTER COLUMN monto DROP NOT NULL;

-- El fijo del que salio cada vencimiento. Un fijo no repite un vencimiento: saltear uno lo da de baja.
ALTER TABLE cuentas_pagar ADD COLUMN fijo_id INTEGER REFERENCES fijos(id);
CREATE UNIQUE INDEX idx_cuentas_pagar_fijo ON cuentas_pagar(fijo_id, vence) WHERE fijo_id IS NOT NULL AND eliminado_en IS NULL;

-- Lo que ya se repetia pasa solo a Fijos: la ultima cuenta de cada serie, si no se dio de baja. Su
-- vencimiento ya esta en Saldos pendientes, asi que el fijo sigue desde el proximo.
DO $$
DECLARE
  c RECORD;
  nuevo INTEGER;
BEGIN
  FOR c IN
    SELECT cp.id, cp.tipo, cp.concepto, cp.monto, cp.vence, cp.repeticion, cp.nota, cp.serie_base, cp.usuario_id
    FROM cuentas_pagar cp
    WHERE cp.eliminado_en IS NULL
      AND cp.repeticion <> 'no'
      AND NOT EXISTS (SELECT 1 FROM cuentas_pagar sig WHERE sig.origen_id = cp.id)
    ORDER BY cp.id
  LOOP
    INSERT INTO fijos (tipo, concepto, monto, frecuencia, desde, generado_hasta, nota, usuario_id)
    VALUES (c.tipo, c.concepto, c.monto, c.repeticion, c.serie_base, c.vence, c.nota, c.usuario_id)
    RETURNING id INTO nuevo;
    UPDATE cuentas_pagar SET fijo_id = nuevo WHERE id = c.id;
  END LOOP;
END $$;
