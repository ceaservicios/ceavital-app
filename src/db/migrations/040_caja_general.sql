-- Caja general (pedido del usuario, 2026-11-06; maqueta aprobada): el efectivo que ya no esta en la
-- caja del turno. Recibe solo el retiro de cada cierre y de ahi salen los pagos grandes (alquiler,
-- proveedores, servicios), que no pasan por la caja del turno y no dan diferencia en el cierre.
-- El saldo no se guarda: se calcula con los retiros de los cierres, los movimientos anotados a mano
-- y los gastos que salieron de Caja general. Asi, corregir un cierre o anular un pago se refleja solo.
-- Aditiva: columnas nuevas con valor por defecto y una tabla nueva.

-- De donde salio cada gasto: la caja del turno, Caja general u otro lado (no descuenta de ninguna).
-- Un pago a un proveedor o de Saldos pendientes que sale de una de las dos cajas sigue siendo un
-- gasto vinculado (sale_de_caja + gasto_caja_id), y el origen se lee de ese gasto.
ALTER TABLE gastos_caja ADD COLUMN origen TEXT NOT NULL DEFAULT 'caja'
  CHECK (origen IN ('caja', 'general', 'otro'));
UPDATE gastos_caja SET origen = 'otro' WHERE medio_pago <> 'efectivo';
ALTER TABLE gastos_caja ADD CONSTRAINT gastos_caja_origen_del_medio CHECK (medio_pago = 'efectivo' OR origen = 'otro');

-- Solo los cierres de aca en adelante pasan a Caja general: los retiros de antes ya se usaron o estan
-- en lo que se cargue como saldo inicial. Por eso las filas que ya estan quedan en FALSE y las nuevas
-- entran en TRUE.
ALTER TABLE cierres_caja ADD COLUMN a_caja_general BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE cierres_caja ALTER COLUMN a_caja_general SET DEFAULT TRUE;

-- Lo que se anota a mano. No se borra: anularlo lo saca de la cuenta y queda en el registro de acciones.
CREATE TABLE caja_general_movimientos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo TEXT NOT NULL CHECK (tipo IN ('inicial', 'ingreso', 'banco', 'dueno')),
  monto BIGINT NOT NULL CHECK (monto > 0),
  fecha DATE NOT NULL,
  detalle TEXT CHECK (char_length(detalle) <= 200),
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  anulado_en TIMESTAMP(0),
  anulado_por INTEGER REFERENCES usuarios(id),
  creado_en TIMESTAMP(0) NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_caja_general_movimientos_fecha ON caja_general_movimientos(fecha);
